export type Copy = typeof en
export type Lang = "en" | "zh"

const I18nContext = createContext<{ lang: Lang; copy: Copy; setLang: (lang: Lang) => void } | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("namepay-lang")
    return saved === "zh" ? "zh" : "en"
  })
  const setLang = (next: Lang) => {
    localStorage.setItem("namepay-lang", next)
    setLangState(next)
  }
  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en"
  }, [lang])
  const value = useMemo(() => ({ lang, copy: lang === "zh" ? zh : en, setLang }), [lang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error("i18n")
  return value
}
